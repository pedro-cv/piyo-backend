// Iteration-2 settings: store selection, dataset releases, map hosting and
// suggestion quota. Loaded by loadV2 from Load().
package config

import (
	"errors"
	"fmt"
	"os"
	"strings"
)

// Store kinds.
const (
	StoreMemory   = "memory"
	StoreSQLite   = "sqlite"
	StorePostgres = "postgres"
)

// Defaults for the new settings.
const (
	DefaultReleasesDir          = "./releases"
	DefaultStyleDir             = "./map/style"
	DefaultTilesDir             = "./map/tiles"
	DefaultMaxSuggestionsPerDay = 5
	// DefaultMaxContributionsPerMonth keeps the review queue small: 3 route
	// contributions per device per calendar month (UTC).
	DefaultMaxContributionsPerMonth = 3
	DefaultDatabaseURL              = "postgres://piyo:piyo@localhost:5432/piyo?sslmode=disable"
)

// V2 holds the settings added in iteration 2 (embedded in Config).
type V2 struct {
	// Store: memory | sqlite | postgres. Default: memory in dev, postgres in prod.
	Store       string
	DatabaseURL string

	// ReleasesDir holds the versioned dataset files produced by piyo-import.
	ReleasesDir string
	// StyleDir holds style-light.json / style-dark.json generated by deploy/tiles.
	StyleDir string
	// TilesDir holds santa-cruz.pmtiles (for size reporting only; Martin serves it).
	TilesDir string
	// PublicBaseURL overrides the base used in absolute URLs (else from the request).
	PublicBaseURL string
	// TilesPublicURL overrides the tile server base (default PublicBaseURL + "/tiles").
	TilesPublicURL string
	// AssetsPublicURL overrides the fonts/sprites base (default PublicBaseURL + "/assets").
	AssetsPublicURL string

	MaxSuggestionsPerDay int
	// MaxContributionsPerMonth caps POST /v1/contributions per device and UTC month.
	MaxContributionsPerMonth int
}

func (c *Config) loadV2() error {
	var err error
	c.Store = strings.ToLower(envString("STORE", ""))
	c.DatabaseURL = envString("DATABASE_URL", DefaultDatabaseURL)
	c.ReleasesDir = envString("RELEASES_DIR", DefaultReleasesDir)
	c.StyleDir = envString("STYLE_DIR", DefaultStyleDir)
	c.TilesDir = envString("TILES_DIR", DefaultTilesDir)
	c.PublicBaseURL = strings.TrimRight(os.Getenv("PUBLIC_BASE_URL"), "/")
	c.TilesPublicURL = strings.TrimRight(os.Getenv("TILES_PUBLIC_URL"), "/")
	c.AssetsPublicURL = strings.TrimRight(os.Getenv("ASSETS_PUBLIC_URL"), "/")
	if c.MaxSuggestionsPerDay, err = envInt("MAX_SUGGESTIONS_PER_DAY", DefaultMaxSuggestionsPerDay); err != nil {
		return err
	}
	if c.MaxContributionsPerMonth, err = envInt("MAX_CONTRIBUTIONS_PER_MONTH", DefaultMaxContributionsPerMonth); err != nil {
		return err
	}
	return nil
}

func (c *Config) validateV2() error {
	if c.Store == "" {
		if c.DevMode {
			c.Store = StoreMemory
		} else {
			c.Store = StorePostgres
		}
	}
	switch c.Store {
	case StoreMemory, StoreSQLite, StorePostgres:
	default:
		return fmt.Errorf("STORE must be memory, sqlite or postgres, got %q", c.Store)
	}
	if c.Store == StorePostgres && c.DatabaseURL == "" {
		return errors.New("DATABASE_URL is required when STORE=postgres")
	}
	if c.MaxSuggestionsPerDay <= 0 {
		return fmt.Errorf("MAX_SUGGESTIONS_PER_DAY must be > 0, got %d", c.MaxSuggestionsPerDay)
	}
	if c.MaxContributionsPerMonth <= 0 {
		return fmt.Errorf("MAX_CONTRIBUTIONS_PER_MONTH must be > 0, got %d", c.MaxContributionsPerMonth)
	}
	return nil
}

// StoreKind returns the resolved store name for logs and /v1/health.
func (c Config) StoreKind() string { return c.Store }
